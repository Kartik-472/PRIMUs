-- The Round 3 market model (packages/engine/src/market.ts): how a market price moves when a trading round clears.
--
--   move = clamp(impact + value + momentum + market + sector + own + news, −10%, +10%), in parts per million
--   impact   = sign(net) × 1% × √(|net| × old price ÷ $10,000)      square-root impact on the money traded
--   value    = 12% × (score-based price − old) ÷ old                  background value investors
--   momentum = 10% × last round's move                                trend followers
--   market, sector (crisis card), own = 0.3%, 0.5%, 0.7% × z          from the committed market seed
--   news     = the organisers' news shocks released with this clearing
--
-- events.market_model = 'SIMPLE' switches back to the original rule (net ÷ 1,000 %, capped at ±10%).
-- Every order of a round still fills at the one new price; nothing about orders, reserves or limits changes.

-- ───────────────────────────── Schema ─────────────────────────────

alter table public.events
  add column market_model text not null default 'REALISTIC' check (market_model in ('REALISTIC', 'SIMPLE')),
  add column market_seed_commitment text check (market_seed_commitment ~ '^[0-9a-f]{64}$'),
  add column market_seed_revealed text;

-- The market seed: generated by the database, its SHA-256 is public from the moment it exists, the seed itself is
-- published at the close. Organisers only (nobody who trades can read it).
create table public.market_secrets (
  event_id uuid primary key references public.events (id) on delete cascade,
  seed text not null check (seed ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now()
);
grant select on public.market_secrets to authenticated;
alter table public.market_secrets enable row level security;
create policy market_secrets_read on public.market_secrets for select to authenticated using ((select app.is_organiser()));

-- What moved each price, for the price chart, the exports and anyone checking the numbers afterwards.
alter table public.round_prices
  add column move_ppm integer,
  add column parts jsonb;

-- News that moves prices: written ahead, kept hidden, published by the clearing of its round, which applies the shock
-- in the same instant (so nobody can trade on it first). Scope MARKET hits every company, CRISIS the companies with
-- one crisis card, COMPANY one company.
alter table public.bulletins
  add column release_round smallint check (release_round between 1 and 9),
  add column shock_bp integer check (shock_bp between -2000 and 2000),
  add column shock_scope text check (shock_scope in ('MARKET', 'CRISIS', 'COMPANY')),
  add column shock_target uuid,
  add check ((shock_bp is null) = (shock_scope is null)),
  add check (shock_scope is null or release_round is not null),
  add check ((shock_scope in ('CRISIS', 'COMPANY')) = (shock_target is not null));
create index bulletins_release_idx on public.bulletins (event_id, release_round) where published_at is null;

-- ───────────────────────────── The model (parity with market.ts) ─────────────────────────────

-- z = (u1 + u2 + u3 + u4 − 2) × √3 from the first four words of SHA-256(seed:market:round:key).
create or replace function app.market_z(p_seed text, p_round integer, p_key text)
returns double precision
language sql immutable strict parallel safe
as $$
  with h as (select extensions.digest(convert_to(p_seed || ':market:' || p_round || ':' || p_key, 'UTF8'), 'sha256') as b),
  w as (
    select ((get_byte(b, i)::bigint << 24) | (get_byte(b, i + 1) << 16) | (get_byte(b, i + 2) << 8) | get_byte(b, i + 3))::double precision
           / 4294967296::double precision as u, i
      from h, unnest(array[0, 4, 8, 12]) as i
  )
  select ((select u from w where i = 0) + (select u from w where i = 4) + (select u from w where i = 8)
          + (select u from w where i = 12) - 2::double precision) * sqrt(3::double precision)
$$;

-- The capped move in parts per million. Same order of operations as marketMove (IEEE doubles round each step the same
-- way in both).
create or replace function app.market_move_ppm(p_old bigint, p_net bigint, p_score bigint, p_last_ppm integer,
                                               p_news_bp integer, p_zm double precision, p_zs double precision,
                                               p_zo double precision)
returns integer
language sql immutable strict parallel safe
as $$
  select greatest(-100000, least(100000, floor((
             sign(p_net)::double precision * 0.01::double precision
               * sqrt((abs(p_net) * p_old)::double precision / 1000000::double precision)
           + (0.12::double precision * (p_score - p_old)::double precision) / p_old::double precision
           + (0.1::double precision * p_last_ppm::double precision) / 1000000::double precision
           + 0.003::double precision * p_zm
           + 0.005::double precision * p_zs
           + 0.007::double precision * p_zo
           + p_news_bp::double precision / 10000::double precision
         ) * 1000000::double precision + 0.5::double precision)))::integer
$$;

-- The parts of the move (as fractions), for round_prices.parts.
create or replace function app.market_parts(p_old bigint, p_net bigint, p_score bigint, p_last_ppm integer,
                                            p_news_bp integer, p_zm double precision, p_zs double precision,
                                            p_zo double precision)
returns jsonb
language sql immutable strict parallel safe
as $$
  select jsonb_build_object(
    'impact', round((sign(p_net) * 0.01 * sqrt((abs(p_net) * p_old)::double precision / 1000000))::numeric, 6),
    'value', round(((0.12 * (p_score - p_old)) / p_old::double precision)::numeric, 6),
    'momentum', round((0.1 * p_last_ppm / 1000000.0)::numeric, 6),
    'market', round((0.003 * p_zm)::numeric, 6),
    'sector', round((0.005 * p_zs)::numeric, 6),
    'own', round((0.007 * p_zo)::numeric, 6),
    'news', round((p_news_bp / 10000.0)::numeric, 6))
$$;

-- The market seed exists from the first call on (the first clearing at the latest); the commitment is public.
create or replace function app.ensure_market_seed(p_event uuid)
returns text
language plpgsql
as $$
declare
  v_seed text;
begin
  select seed into v_seed from public.market_secrets where event_id = p_event;
  if v_seed is null then
    v_seed := encode(extensions.gen_random_bytes(32), 'hex');
    insert into public.market_secrets (event_id, seed) values (p_event, v_seed)
    on conflict (event_id) do nothing;
    select seed into v_seed from public.market_secrets where event_id = p_event;
    update public.events set market_seed_commitment = app.sha256_hex(v_seed) where id = p_event;
  end if;
  return v_seed;
end
$$;

-- Organisers: create (or show) the market seed's commitment ahead of Round 3, to put on the big screen.
create or replace function public.market_seed_commitment(p_event uuid)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
begin
  perform app.require_organiser();
  perform app.ensure_market_seed(p_event);
  return app.ok(jsonb_build_object('commitment', (select market_seed_commitment from public.events where id = p_event)));
end
$$;

-- Organisers: choose the price model (only before the first clearing).
create or replace function public.set_market_model(p_event uuid, p_model text)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
begin
  perform app.require_organiser();
  if p_model not in ('REALISTIC', 'SIMPLE') then
    raise exception 'the market model is REALISTIC or SIMPLE';
  end if;
  if exists (select 1 from public.rounds where event_id = p_event and status = 'CLEARED') then
    return app.fail('TOO_LATE', 'The price model can only change before the first trading round clears.');
  end if;
  update public.events set market_model = p_model where id = p_event;
  return app.ok(jsonb_build_object('model', p_model));
end
$$;

-- Organisers: write a news item that moves prices, released with the clearing of a round.
create or replace function public.schedule_news(p_event uuid, p_round integer, p_title text, p_body text,
                                                p_scope text, p_target uuid, p_shock_bp integer)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_b public.bulletins;
begin
  perform app.require_organiser();
  if p_round is null or p_round not between 1 and 9 then
    raise exception 'news is released with a trading round, 1 to 9';
  end if;
  if exists (select 1 from public.rounds where event_id = p_event and number = p_round and status <> 'OPEN' and status <> 'SCHEDULED') then
    return app.fail('TOO_LATE', 'That round has already closed.');
  end if;
  if p_shock_bp is null or p_shock_bp = 0 or abs(p_shock_bp) > 2000 then
    raise exception 'a news shock is −20%% to +20%%, not zero';
  end if;
  if p_scope = 'MARKET' and p_target is not null then
    raise exception 'market-wide news has no target';
  end if;
  if p_scope = 'CRISIS' and not exists (select 1 from public.crisis_cards where id = p_target and event_id = p_event) then
    raise exception 'no such crisis card';
  end if;
  if p_scope = 'COMPANY' and not exists (select 1 from public.companies where id = p_target and event_id = p_event) then
    raise exception 'no such company';
  end if;
  if length(btrim(coalesce(p_title, ''))) not between 1 and 140 then
    raise exception 'a bulletin title is 1 to 140 characters';
  end if;
  insert into public.bulletins (event_id, kind, title, body, created_by, release_round, shock_bp, shock_scope, shock_target)
  values (p_event, 'GENERAL', btrim(p_title), coalesce(p_body, ''), auth.uid(), p_round, p_shock_bp, p_scope,
          case when p_scope = 'MARKET' then null else p_target end)
  returning * into v_b;
  return app.ok(jsonb_build_object('bulletin', to_jsonb(v_b)));
end
$$;

-- Organisers: drop a scheduled news item before it is released.
create or replace function public.cancel_news(p_bulletin uuid)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
begin
  perform app.require_organiser();
  delete from public.bulletins where id = p_bulletin and published_at is null and release_round is not null;
  if not found then
    return app.fail('NOT_FOUND', 'No unreleased news item with that id.');
  end if;
  return app.ok(jsonb_build_object('cancelled', p_bulletin));
end
$$;

-- After the close the seed is published, so anyone can recompute every move.
create or replace function app.close_market_and_reveal() returns trigger
language plpgsql
as $$
begin
  if new.market_closed_at is not null and old.market_closed_at is null then
    new.market_seed_revealed := (select seed from public.market_secrets where event_id = new.id);
  end if;
  return new;
end
$$;
create trigger events_reveal_market_seed before update of market_closed_at on public.events
  for each row execute function app.close_market_and_reveal();

-- ───────────────────────────── Clearing ─────────────────────────────

-- As in 20261106000008_trading.sql, with the price computed by the market model.
create or replace function app.clear_round(p_round uuid, p_force boolean default false)
returns jsonb
language plpgsql
as $$
declare
  v_round public.rounds;
  v_prev public.rounds;
  v_event public.events;
  v_seed text;
  v_zm double precision;
  v_news public.bulletins;
  v_txn uuid := gen_random_uuid();
  v_exchange_cash bigint;
  v_started timestamptz := clock_timestamp();
begin
  select * into v_round from public.rounds where id = p_round for no key update;
  if v_round.id is null then
    raise exception 'no such round';
  end if;
  if v_round.status = 'CLEARED' then
    return app.ok(jsonb_build_object('already', true, 'round', v_round.number));
  end if;
  if not p_force and now() < v_round.closes_at then
    raise exception 'round % has not reached its closing time', v_round.number;
  end if;
  if v_round.number > 1 then
    select * into v_prev from public.rounds where event_id = v_round.event_id and number = v_round.number - 1;
    if v_prev.status <> 'CLEARED' then
      raise exception 'round % must be cleared before round %', v_prev.number, v_round.number;
    end if;
  end if;

  -- Every team, in id order, before reading the book: an order in flight commits first, a later one finds the
  -- round closed.
  update public.rounds set status = 'CLOSED', closed_at = coalesce(closed_at, now()) where id = v_round.id;
  perform 1 from public.teams where event_id = v_round.event_id order by id for no key update;

  select * into v_event from public.events where id = v_round.event_id;
  if v_event.market_model = 'REALISTIC' then
    v_seed := app.ensure_market_seed(v_round.event_id);
    v_zm := app.market_z(v_seed, v_round.number, 'market');
  end if;

  perform set_config('app.price_writer', 'CLEARING', true);

  with book as (
    select o.company_id,
           sum(o.qty) filter (where o.type = 'BUY') as buy,
           sum(o.qty) filter (where o.type = 'SELL') as sell
      from public.orders o where o.round_id = v_round.id and o.status = 'PENDING'
     group by o.company_id
  ),
  news as (
    select c.id as company_id, sum(b.shock_bp)::integer as bp
      from public.bulletins b
      join public.companies c on c.event_id = b.event_id
       and (b.shock_scope = 'MARKET'
         or (b.shock_scope = 'CRISIS' and c.crisis_card_id = b.shock_target)
         or (b.shock_scope = 'COMPANY' and c.id = b.shock_target))
     where b.event_id = v_round.event_id and b.release_round = v_round.number and b.published_at is null
       and b.shock_bp is not null
     group by c.id
  ),
  inp as (
    select c.id, c.event_id, c.market_price as old, c.score_price as score,
           coalesce(a.buy, 0) as buy, coalesce(a.sell, 0) as sell, coalesce(a.buy, 0) - coalesce(a.sell, 0) as net,
           coalesce((select rp.move_ppm from public.round_prices rp
                      where rp.round_id = v_prev.id and rp.company_id = c.id and rp.kind = 'CLEARING'), 0) as last_ppm,
           coalesce(n.bp, 0) as news_bp,
           case when v_seed is not null
                then app.market_z(v_seed, v_round.number, 'sector:' || coalesce(c.crisis_card_id::text, 'none')) end as zs,
           case when v_seed is not null then app.market_z(v_seed, v_round.number, 'company:' || c.id::text) end as zo
      from public.companies c
      left join book a on a.company_id = c.id
      left join news n on n.company_id = c.id
     where c.event_id = v_round.event_id and c.market_price is not null
  ),
  mv as (
    select inp.*,
           case when v_seed is null then null
                else app.market_move_ppm(old, net, coalesce(score, old), last_ppm, news_bp, v_zm, zs, zo) end as ppm
      from inp
  )
  insert into public.round_prices (event_id, company_id, round_id, kind, market_before, market_after, score_before, score_after,
                                   buy_qty, sell_qty, net_qty, capped_net, move_ppm, parts)
  select mv.event_id, mv.id, v_round.id, 'CLEARING', mv.old,
         case when mv.ppm is null then app.clearing_price(mv.old, mv.net)
              else greatest(1, app.mul_rate(mv.old, 1000000 + mv.ppm, 1000000)) end,
         mv.score, mv.score, mv.buy, mv.sell, mv.net, app.capped_net(mv.net),
         coalesce(mv.ppm, app.capped_net(mv.net)::integer * 10),
         case when mv.ppm is null then null
              else app.market_parts(mv.old, mv.net, coalesce(mv.score, mv.old), mv.last_ppm, mv.news_bp, v_zm, mv.zs, mv.zo) end
    from mv;

  update public.companies c set market_price = rp.market_after
    from public.round_prices rp
   where rp.round_id = v_round.id and rp.kind = 'CLEARING' and rp.company_id = c.id;
  perform set_config('app.price_writer', '', true);

  -- The news released with this round goes public now, together with the prices it moved.
  for v_news in
    update public.bulletins set published_at = now()
     where event_id = v_round.event_id and release_round = v_round.number and published_at is null
       and shock_bp is not null
    returning *
  loop
    perform app.broadcast(v_round.event_id, 'bulletin', jsonb_build_object('id', v_news.id, 'bulletin_kind', v_news.kind,
                                                                           'title', v_news.title, 'body', v_news.body));
  end loop;

  update public.orders o
     set status = 'FILLED', fill_price = c.market_price, filled_at = now(), updated_at = now()
    from public.companies c
   where o.round_id = v_round.id and o.status = 'PENDING' and c.id = o.company_id;

  create temporary table if not exists _fills (team_id uuid, company_id uuid, price int, s int, b int) on commit drop;
  truncate _fills;
  insert into _fills
  select o.team_id, o.company_id, min(o.fill_price),
         coalesce(sum(o.qty) filter (where o.type = 'SELL'), 0), coalesce(sum(o.qty) filter (where o.type = 'BUY'), 0)
    from public.orders o where o.round_id = v_round.id and o.status = 'FILLED'
   group by o.team_id, o.company_id;

  insert into public.holdings (event_id, team_id, company_id, qty, cost_cents)
  select v_round.event_id, f.team_id, f.company_id, 0, 0 from _fills f
  on conflict (team_id, company_id) do nothing;

  if exists (select 1 from _fills f join public.holdings h on h.team_id = f.team_id and h.company_id = f.company_id
              where f.s > h.qty) then
    raise exception 'a team sells more than it holds; refusing to clear round %', v_round.number;
  end if;

  update public.holdings h
     set qty = h.qty - f.s + f.b,
         cost_cents = h.cost_cents - case when f.s > 0 then app.mul_rate(h.cost_cents, f.s, h.qty) else 0 end
                      + f.b::bigint * f.price,
         updated_at = now()
    from _fills f
   where h.team_id = f.team_id and h.company_id = f.company_id;

  update public.teams t
     set cash_cents = t.cash_cents + x.delta
    from (select team_id, sum((s - b)::bigint * price) as delta from _fills group by team_id) x
   where t.id = x.team_id;

  -- Ledger: one row per filled order for the team, one row per company for the exchange.
  insert into public.ledger_entries (event_id, txn_id, kind, team_id, company_id, cash_delta_cents, share_delta,
                                     price_cents, round_id, ref_table, ref_id, memo)
  select o.event_id, v_txn, 'TRADE', o.team_id, o.company_id,
         case when o.type = 'SELL' then 1 else -1 end * o.qty::bigint * o.fill_price,
         case when o.type = 'BUY' then o.qty else -o.qty end,
         o.fill_price, o.round_id, 'orders', o.id, o.type::text || ' round ' || v_round.number
    from public.orders o where o.round_id = v_round.id and o.status = 'FILLED';
  insert into public.ledger_entries (event_id, txn_id, kind, team_id, company_id, cash_delta_cents, share_delta, price_cents, round_id, memo)
  select rp.event_id, v_txn, 'TRADE', null, rp.company_id, rp.net_qty::bigint * rp.market_after, -rp.net_qty,
         rp.market_after, v_round.id, 'Exchange, round ' || v_round.number
    from public.round_prices rp
   where rp.round_id = v_round.id and rp.kind = 'CLEARING' and rp.buy_qty + rp.sell_qty > 0;

  select coalesce(sum(net_qty::bigint * market_after), 0) into v_exchange_cash
    from public.round_prices where round_id = v_round.id and kind = 'CLEARING';
  update public.events set exchange_cash_cents = exchange_cash_cents + v_exchange_cash where id = v_round.event_id;

  -- The public ledger: every filled trade (team code, company, side, quantity, price) and the round's totals.
  insert into public.public_ledger (event_id, txn_id, kind, label, team_code, company_id, ticker, side, shares, price_cents,
                                    cash_cents, round_number)
  select o.event_id, v_txn, 'TRADE', t.code || ' ' || lower(o.type::text) || 's ' || o.qty || ' ' || c.ticker,
         t.code, o.company_id, c.ticker, o.type::text, o.qty, o.fill_price, o.qty::bigint * o.fill_price, v_round.number
    from public.orders o join public.teams t on t.id = o.team_id join public.companies c on c.id = o.company_id
   where o.round_id = v_round.id and o.status = 'FILLED'
   order by c.ticker, o.type, t.code;
  insert into public.public_ledger (event_id, txn_id, kind, label, company_id, ticker, shares, price_cents, round_number, details)
  select rp.event_id, v_txn, 'ROUND', 'Round ' || v_round.number, rp.company_id, c.ticker, rp.net_qty, rp.market_after,
         v_round.number,
         jsonb_build_object('buy', rp.buy_qty, 'sell', rp.sell_qty, 'net', rp.net_qty, 'before', rp.market_before)
    from public.round_prices rp join public.companies c on c.id = rp.company_id
   where rp.round_id = v_round.id and rp.kind = 'CLEARING' and rp.buy_qty + rp.sell_qty > 0;

  update public.rounds set status = 'CLEARED', cleared_at = now() where id = v_round.id;

  perform app.broadcast(v_round.event_id, 'round_cleared', jsonb_build_object('round', v_round.number));

  return app.ok(jsonb_build_object('round', v_round.number,
                                   'orders', (select count(*) from public.orders where round_id = v_round.id and status = 'FILLED'),
                                   'ms', round(extract(epoch from clock_timestamp() - v_started) * 1000)));
end
$$;

